test('partial success replaces only successful-page AI data and records one undo entry', async () => {
    const state = oldState();
    let historyWrites = 0;
    const result = await executeReanalysisTransaction({
        state,
        pages: [1, 2],
        analyzePage: async pageIndex => {
            if (pageIndex === 2) throw new Error('HTTP 500');
            return { status: 'success', dimensions: [{ text: 'new-dim-1' }] };
        },
        stagePage: async (_raw, pageIndex) => ({
            stamps: [{ uuid: `new-ai-${pageIndex}`, pageIndex, isAutoGenerated: true }],
            viewBoxes: [{ id: `new-vb-${pageIndex}`, pageIndex }],
            basicDimensions: [{ id: `new-basic-${pageIndex}`, pageIndex }],
            datumReferences: [{ id: `new-ref-${pageIndex}`, pageIndex }],
            clusters: [{ clusterId: `new-cluster-${pageIndex}`, pageIndex }],
            cacheValue: [`new-dim-${pageIndex}`],
        }),
        pushHistory: () => { historyWrites += 1; },
    });

    assert.equal(result.status, 'partial');
    assert.deepEqual(result.succeededPages, [1]);
    assert.deepEqual(result.failedPages, [2]);
    assert.deepEqual(
        state.stamps.map(stamp => stamp.uuid).sort(),
        ['ai-2', 'manual-1', 'new-ai-1'],
    );
    assert.deepEqual(state.viewBoxes.map(box => box.id).sort(), ['new-vb-1', 'vb-2']);
    assert.deepEqual(state.basicDimensions.map(item => item.id).sort(), ['basic-2', 'new-basic-1']);
    assert.deepEqual(state.datumReferences.map(item => item.id).sort(), ['new-ref-1', 'ref-2']);
    assert.deepEqual(state.selectedUUIDs.sort(), ['ai-2', 'manual-1']);
    assert.deepEqual(state.l1Cache.get(1), ['new-dim-1']);
    assert.deepEqual(state.l1Cache.get(2), ['old-dim-2']);
    assert.equal(historyWrites, 1);
});

test('multi-page partial commit preserves the shadow page and reports its closed authority', async () => {
    const state = oldState();
    let stageCalls = 0;
    let historyWrites = 0;
    const result = await executeReanalysisTransaction({
        state,
        pages: [1, 2],
        analyzePage: async pageIndex => pageIndex === 1
            ? { status: 'success', dimensions: [{ text: 'new-dim-1' }] }
            : {
                status: 'success',
                dimensions: [],
                view_boxes: [{ x: 2, y: 3, w: 4, h: 5 }],
                analysis_mode_v1: {
                    schema_version: 'analysis_mode_v1',
                    effective_mode: 'shadow',
                    display_allowed: false,
                },
            },
        stagePage: async (_raw, pageIndex) => {
            stageCalls += 1;
            return {
                stamps: [{ uuid: `new-ai-${pageIndex}`, pageIndex, isAutoGenerated: true }],
                viewBoxes: [{ id: `new-vb-${pageIndex}`, pageIndex }],
                cacheValue: [`new-dim-${pageIndex}`],
            };
        },
        pushHistory: () => { historyWrites += 1; },
    });

    assert.equal(result.status, 'partial');
    assert.deepEqual(result.succeededPages, [1]);
    assert.deepEqual(result.failedPages, [2]);
    assert.deepEqual(result.pageFailures, [{
        pageIndex: 2,
        code: 'analysis_result_not_product_eligible',
        reasons: ['analysis_mode_not_product', 'analysis_mode_display_closed'],
    }]);
    assert.equal(stageCalls, 1);
    assert.equal(historyWrites, 1);
    assert.deepEqual(state.viewBoxes.map(box => box.id).sort(), ['new-vb-1', 'vb-2']);
    assert.deepEqual(state.basicDimensions.map(item => item.id), ['basic-2']);
    assert.deepEqual(state.datumReferences.map(item => item.id), ['ref-2']);
    assert.deepEqual(state.clusters.map(item => item.clusterId), ['cluster-2']);
    assert.deepEqual(state.l1Cache.get(1), ['new-dim-1']);
    assert.deepEqual(state.l1Cache.get(2), ['old-dim-2']);
    assert.deepEqual([...state.currentAnalyzedPages], [1, 2]);
    assert.ok(state.stamps.some(stamp => stamp.uuid === 'ai-2'));
    assert.ok(state.selectedUUIDs.includes('ai-2'));
});

function successfulResult(pageIndex) {
    return { status: 'success', dimensions: [{ text: String(pageIndex) }] };
}

function stagedPage(_raw, pageIndex) {
    return {
        stamps: [{ uuid: `new-ai-${pageIndex}`, pageIndex, isAutoGenerated: true }],
        cacheValue: [`new-${pageIndex}`],
    };
}

test('six-page analysis requests every page exactly once and reports exact progress', async () => {
    const state = oldState();
    const calls = [];
    const progress = [];
    const pages = Array.from({ length: 6 }, (_, index) => index + 1);
    const result = await executeReanalysisTransaction({
        state,
        pages,
        analyzePage: async pageIndex => {
            calls.push(pageIndex);
            return successfulResult(pageIndex);
        },
        stagePage: stagedPage,
        onProgress: update => progress.push(update),
    });

    assert.equal(result.status, 'success');
    assert.deepEqual(calls, pages);
    assert.deepEqual(progress.map(item => item.completed), pages);
    assert.ok(progress.every(item => item.total === 6));
});


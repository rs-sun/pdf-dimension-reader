function oldState() {
    return {
        stamps: [
            { uuid: 'ai-1', pageIndex: 1, isAutoGenerated: true },
            { uuid: 'manual-1', pageIndex: 1, isAutoGenerated: false },
            { uuid: 'ai-2', pageIndex: 2, isAutoGenerated: true },
        ],
        reviewWorkspace: {
            envelopes: [{ opaque: 'old-review-envelope' }],
            decisions: { opaque: { status: 'pending' } },
            selectedCandidateId: 'opaque',
        },
        viewBoxes: [{ id: 'vb-1', pageIndex: 1 }, { id: 'vb-2', pageIndex: 2 }],
        basicDimensions: [{ id: 'basic-1', pageIndex: 1 }, { id: 'basic-2', pageIndex: 2 }],
        datumReferences: [{ id: 'ref-1', pageIndex: 1 }, { id: 'ref-2', pageIndex: 2 }],
        clusters: [
            { clusterId: 'cluster-1', pageIndex: 1 },
            { clusterId: 'cluster-2', pageIndex: 2 },
        ],
        l1Cache: new Map([[1, ['old-dim-1']], [2, ['old-dim-2']]]),
        currentAnalyzedPages: new Set([1, 2]),
        selectedUUIDs: ['ai-1', 'manual-1', 'ai-2'],
        historyStack: [{ marker: 'old-history' }],
        historyIndex: 0,
        documentGeneration: 3,
        isAnalysisRunning: false,
    };
}

function assertCoreUnchanged(state, before, { includeHistory = true } = {}) {
    assert.deepEqual(state.stamps, before.stamps);
    assert.deepEqual(state.reviewWorkspace, before.reviewWorkspace);
    assert.deepEqual(state.viewBoxes, before.viewBoxes);
    assert.deepEqual(state.basicDimensions, before.basicDimensions);
    assert.deepEqual(state.datumReferences, before.datumReferences);
    assert.deepEqual(state.clusters, before.clusters);
    assert.deepEqual([...state.l1Cache], [...before.l1Cache]);
    assert.deepEqual([...state.currentAnalyzedPages], [...before.currentAnalyzedPages]);
    assert.deepEqual(state.selectedUUIDs, before.selectedUUIDs);
    if (includeHistory) {
        assert.deepEqual(state.historyStack, before.historyStack);
        assert.equal(state.historyIndex, before.historyIndex);
    }
}

test('timeout, HTTP error, fail-closed, and empty responses leave existing page data untouched', async () => {
    const failures = [
        async () => { throw Object.assign(new Error('timeout'), { name: 'AbortError' }); },
        async () => { throw new Error('HTTP 503'); },
        async () => ({ status: 'unsupported', dimensions: [] }),
        async () => ({ status: 'success', dimensions: [], view_boxes: [] }),
    ];

    for (const analyzePage of failures) {
        const state = oldState();
        const before = structuredClone(state);
        const result = await executeReanalysisTransaction({
            state,
            pages: [1],
            analyzePage,
            stagePage: () => { throw new Error('must not stage failed response'); },
            pushHistory: () => { throw new Error('must not write history on failure'); },
        });

        assert.equal(result.status, 'failed');
        assert.equal(result.statePreserved, true);
        assert.equal(result.pageFailures.length, 1);
        assert.equal(result.pageFailures[0].pageIndex, 1);
        assertCoreUnchanged(state, before);
        assert.equal(state.isAnalysisRunning, false);
    }
});

test('non-retryable transport failure stops the remaining page requests and preserves its code', async () => {
    const state = oldState();
    const before = structuredClone(state);
    const calls = [];
    const result = await executeReanalysisTransaction({
        state,
        pages: [1, 2, 3],
        analyzePage: async pageIndex => {
            calls.push(pageIndex);
            throw Object.assign(new Error('request exceeds whole-body limit'), {
                code: 'request_body_too_large',
                status: 413,
                retryable: false,
            });
        },
        stagePage: () => { throw new Error('must not stage transport failure'); },
        pushHistory: () => { throw new Error('must not commit transport failure'); },
    });

    assert.deepEqual(calls, [1]);
    assert.equal(result.status, 'failed');
    assert.deepEqual(result.failedPages, [1]);
    assert.deepEqual(result.skippedPages, [2, 3]);
    assert.deepEqual(result.pageFailures, [{
        pageIndex: 1,
        code: 'request_body_too_large',
        reasons: [],
        message: 'request exceeds whole-body limit',
        status: 413,
        retryable: false,
    }]);
    assertCoreUnchanged(state, before);
});


/**
 * 发起矢量解析请求，返回后端统一 JSON 响应对象。
 *
 * @param {number} pageIndex  1-indexed 页码
 * @param {{signal?:AbortSignal}} [options]
 * @returns {Promise<object|null>}
 *   成功：后端 JSON（含 pdf_type, dimensions, page_width, page_height 等字段）
 *   取消/普通网络失败：null；结构化 API/transport 失败：记录并抛出
 */
export async function runAnalysis(pageIndex, { signal, vectorDebugRequest } = {}) {
    if (!state.currentPdfBuffer) {
        alert('请先打开图纸文档！');
        return null;
    }

    const strictCapabilityBlock = _strictVectorOnlyAnalysisBlock();
    if (strictCapabilityBlock) {
        alert(_formatStrictVectorOnlyBlockAlert(strictCapabilityBlock));
        return null;
    }

    const controller = new AbortController();
    let timedOut = false;
    const timeoutId  = setTimeout(() => {
        timedOut = true;
        controller.abort();
    }, 300000); // CPU 模式 5 分钟上限
    const abortFromCaller = () => controller.abort();
    signal?.addEventListener('abort', abortFromCaller, { once: true });
    if (signal?.aborted) controller.abort();

    const t0 = performance.now();
    const runEntry = {
        ts: new Date().toISOString(),
        page: pageIndex,
        debug_log: null,
        dimensions: null,
        basic_dimensions: null,
        references: null,
        view_boxes: null,
        review_candidates_v1: null,
        durationMs: 0,
        ok: false,
        error: null,
        http_status: null,
        code: null,
        recovery: null,
        reasons: [],
        trace_id: null,
        estimated_request_body_bytes: null,
        max_request_body_bytes: state.legacyJsonBase64MaxRequestBodyBytes,
        r33_m1_phrase_chain_audit_v1: null,
    };

    try {
        const preparedRequest = prepareJsonBase64Body(
            state.currentPdfBuffer,
            {
                page: pageIndex,
                dpi: 200,
                settings: buildAnalyzeSettingsPayload({ vectorDebugRequest }),
            },
            state.legacyJsonBase64MaxRequestBodyBytes,
        );
        runEntry.estimated_request_body_bytes = preparedRequest.requestBodyBytes;
        const response = await fetch(ANALYZE_URL, {
            method:  'POST',
            headers: { 'Content-Type': 'application/json' },
            body:    preparedRequest.body,
            signal:  controller.signal,
        });

        const result = await readResponsePayload(response);
        if (response.ok && !_isRecord(result)) {
            throw _invalidResponsePayloadError(response, {
                estimatedRequestBodyBytes: preparedRequest.requestBodyBytes,
                maxRequestBodyBytes: state.legacyJsonBase64MaxRequestBodyBytes,
            });
        }
        _recordAnalyzePayload(runEntry, result, response.status);
        updateRecognitionCapabilitiesFromPayload(result);

        if (!response.ok) {
            if ([413, 502, 504].includes(response.status)) {
                throw normalizeTransportError(response, result, {
                    estimatedRequestBodyBytes: preparedRequest.requestBodyBytes,
                    maxRequestBodyBytes: state.legacyJsonBase64MaxRequestBodyBytes,
                });
            }
            throw new AnalysisApiError({ response, payload: result });
        }

        if (result.debug_log) {
            state.lastDebugLog = result.debug_log;
        }
        if (result.dimensions) {
            state.lastDimensions = result.dimensions;
        }
        if (result.basic_dimensions) {
            state.lastBasicDimensions = result.basic_dimensions;
        }

        if (result.status !== 'success') {
            throw new AnalysisApiError({ response, payload: result });
        }
        const hasDimensions = Array.isArray(result.dimensions) && result.dimensions.length > 0;
        const hasBasicDimensions = Array.isArray(result.basic_dimensions)
            && result.basic_dimensions.length > 0;
        const hasDatumReferences = Array.isArray(result.references)
            && result.references.some(ref => ref?.type === 'datum_reference');
        const hasViewBoxes = Array.isArray(result.view_boxes)
            && result.view_boxes.length > 0;
        const hasNotes = Array.isArray(result.notes) && result.notes.length > 0;
        const hasReviewCandidatesV1 = Object.hasOwn(result, REVIEW_CANDIDATES_ROOT_KEY);
        if (!hasDimensions && !hasBasicDimensions && !hasDatumReferences
            && !hasViewBoxes && !hasNotes && !hasReviewCandidatesV1) {
            alert('智能解析未在当前页面找到可识别的尺寸标注。');
            return null;
        }

        runEntry.ok = true;
        return result;

    } catch (err) {
        runEntry.error = err.name === 'AbortError'
            ? (timedOut ? 'timeout(300s)' : 'cancelled')
            : (err.message || String(err));
        if (err.name === 'AbortError') {
            runEntry.code = timedOut ? 'client_deadline_exceeded' : 'cancelled';
        } else if (err instanceof TransportError) {
            _recordTransportError(runEntry, err);
        }
        if (err.name === 'AbortError' && timedOut) {
            alert('智能解析请求超时（300s）！请检查后端服务是否正常运行。');
        } else if (err instanceof TransportError) {
            alert(_formatTransportErrorAlert('智能解析失败', err));
        } else if (err instanceof AnalysisApiError) {
            alert(_formatAnalysisApiErrorAlert(err));
        } else if (err.name !== 'AbortError') {
            alert('智能解析失败：\n' + err.message);
        }
        if (err instanceof AnalysisApiError || err instanceof TransportError) throw err;
        return null;
    } finally {
        clearTimeout(timeoutId);
        signal?.removeEventListener('abort', abortFromCaller);
        runEntry.durationMs = Math.round(performance.now() - t0);
        pushBounded(state.analyzeRuns, runEntry, DEBUG_LOG_CAPS.analyzeRuns);
    }
}



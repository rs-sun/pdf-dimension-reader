// 把当前识别选项整理成 /analyze 的 settings 字段（Phase 1：尺寸主识别轴）
export function createVectorDebugRequestBudget() {
    let allocatedPages = 0;
    let remainingOverlays = VECTOR_DEBUG_MAX_WORKSPACE_OVERLAYS;
    return Object.freeze({
        take() {
            if (allocatedPages >= VECTOR_DEBUG_MAX_WORKSPACE_PAGES) {
                return Object.freeze({ enabled: false, overlayLimit: 0 });
            }
            allocatedPages += 1;
            const overlayLimit = Math.min(
                VECTOR_LAYER_DEBUG_MAX_PAGE_OVERLAYS,
                remainingOverlays,
            );
            remainingOverlays -= overlayLimit;
            return Object.freeze({ enabled: true, overlayLimit });
        },
    });
}

export function buildAnalyzeSettingsPayload({ vectorDebugRequest } = {}) {
    const isVectorOnly = state.recognitionSettings.dimension_path === 'vector_only';
    const payload = {
        dimension_path: state.recognitionSettings.dimension_path,
        // Strict backend contract has no view-seg fallback. Keep the user's
        // compatible-mode preference in state, but never send a known-invalid
        // watershed/minesweeper choice on a vector_only request.
        view_seg: isVectorOnly ? 'yolo' : state.recognitionSettings.view_seg,
        gdt_backend: state.recognitionSettings.gdt_backend,
    };
    if (!isVectorOnly) {
        payload.ocr_engine = state.recognitionSettings.ocr_engine;
    }
    // 分层矢量诊断是显式、会话级 opt-in。关闭时连请求键都不存在，
    // 以保持现有 /analyze 请求合同不变；后端仍必须把它当旁路诊断。
    const requestEnabled = vectorDebugRequest === undefined
        || vectorDebugRequest?.enabled === true;
    const requestedOverlayLimit = vectorDebugRequest === undefined
        ? VECTOR_LAYER_DEBUG_MAX_PAGE_OVERLAYS
        : vectorDebugRequest?.overlayLimit;
    if (state.vectorDebugState?.enabled === true
            && requestEnabled
            && Number.isInteger(requestedOverlayLimit)
            && requestedOverlayLimit >= 0
            && requestedOverlayLimit <= VECTOR_LAYER_DEBUG_MAX_PAGE_OVERLAYS) {
        payload.vector_layer_debug = {
            schema_version: 'vector_layer_debug_request_v1',
            include_overlays: requestedOverlayLimit > 0,
            overlay_limit: requestedOverlayLimit,
        };
    }
    return payload;
}

export const STRICT_MANUAL_STAMP_OCR_MESSAGE =
    '严格矢量模式下手绘章不做自动识别，请手动填写';

export function createStampOcrRequestGate({
    getDimensionPath,
    requestOcr,
    notify,
}) {
    let strictNoticeShown = false;
    return async function requestStampOcrIfAllowed(stamp) {
        if (!stamp || stamp.isAutoGenerated || !stamp.crop) return null;
        if (getDimensionPath?.() === 'vector_only') {
            if (!strictNoticeShown) {
                strictNoticeShown = true;
                notify?.(STRICT_MANUAL_STAMP_OCR_MESSAGE);
            }
            return null;
        }
        return requestOcr?.(stamp) ?? null;
    };
}

function _isRecord(value) {
    return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function _backendReasons(payload) {
    return Array.isArray(payload?.reasons)
        ? payload.reasons.filter(reason => typeof reason === 'string')
        : [];
}

function _analysisFailureDiagnostics(payload) {
    const candidates = [
        payload?.details,
        payload?.r33_m1_phrase_chain_audit_v1?.details,
    ];
    for (const details of candidates) {
        if (!_isRecord(details)) continue;
        const firstFailedStage = (
            typeof details.first_failed_stage === 'string'
                ? details.first_failed_stage.trim()
                : ''
        );
        if (!firstFailedStage) continue;
        const error = _isRecord(details.error) ? details.error : null;
        const errorCode = typeof error?.code === 'string'
            ? error.code.trim()
            : '';
        const detailReasons = Array.isArray(details.reasons)
            ? details.reasons.filter(
                reason => typeof reason === 'string' && reason,
            )
            : [];
        const errorReasons = Array.isArray(error?.reasons)
            ? error.reasons.filter(
                reason => typeof reason === 'string' && reason,
            )
            : [];
        return {
            firstFailedStage,
            errorCode,
            reasons: detailReasons.length > 0
                ? detailReasons
                : errorReasons,
        };
    }
    return null;
}

export class AnalysisApiError extends Error {
    constructor({ response, payload }) {
        const status = Number.isInteger(response?.status) ? response.status : null;
        const statusText = typeof response?.statusText === 'string'
            ? response.statusText.trim()
            : '';
        const backendMessage = typeof payload?.message === 'string'
            ? payload.message.trim()
            : '';
        const fallback = status === null
            ? 'Analysis request failed'
            : `HTTP ${status}${statusText ? ` ${statusText}` : ''}`;
        super(backendMessage || fallback);
        this.name = 'AnalysisApiError';
        this.code = typeof payload?.code === 'string' && payload.code
            ? payload.code
            : (status === null ? 'analysis_request_failed' : `http_${status}`);
        this.reasons = _backendReasons(payload);
        this.trace = typeof payload?.trace_id === 'string' && payload.trace_id
            ? payload.trace_id
            : null;
        this.status = status;
        this.payload = payload;
        this.recovery = typeof payload?.recovery === 'string' && payload.recovery
            ? payload.recovery
            : null;
        this.retryable = typeof payload?.retryable === 'boolean'
            ? payload.retryable
            : true;
        this.diagnostics = _analysisFailureDiagnostics(payload);
    }
}

function _formatAnalysisApiErrorAlert(error) {
    const lines = ['智能解析失败：'];
    if (error.status !== null) lines.push(`HTTP ${error.status}`);
    lines.push(`code: ${error.code}`);
    if (error.reasons.length > 0) lines.push(`reasons: ${error.reasons.join(', ')}`);
    if (error.diagnostics?.firstFailedStage) {
        lines.push(`failed_stage: ${error.diagnostics.firstFailedStage}`);
    }
    if (error.diagnostics?.errorCode) {
        lines.push(`stage_error: ${error.diagnostics.errorCode}`);
    }
    if (error.diagnostics?.reasons.length > 0) {
        lines.push(`stage_reasons: ${error.diagnostics.reasons.join(', ')}`);
    }
    if (error.trace) lines.push(`trace_id: ${error.trace}`);
    if (error.recovery === 'restart_backend_required') {
        const guidance = formatStrictRuntimeReason(error.code)
            || '需重启后端后恢复严格模式';
        lines.push(`恢复指引：${guidance}。`);
    }
    if (error.message) lines.push(`message: ${error.message}`);
    return lines.join('\n');
}

function _formatTransportErrorAlert(title, error) {
    const lines = [`${title}：`];
    if (error.status !== null) lines.push(`HTTP ${error.status}`);
    lines.push(`code: ${error.code}`);
    if (error.estimatedRequestBodyBytes !== null) {
        lines.push(`预计请求体: ${error.estimatedRequestBodyBytes} bytes`);
    }
    if (error.maxRequestBodyBytes !== null) {
        lines.push(`服务端上限: ${error.maxRequestBodyBytes} bytes`);
    }
    if (error.message) lines.push(`message: ${error.message}`);
    return lines.join('\n');
}

function _invalidResponsePayloadError(response, {
    estimatedRequestBodyBytes = null,
    maxRequestBodyBytes = null,
} = {}) {
    return new TransportError({
        code: 'invalid_response_payload',
        message: '服务端成功响应不符合预期 JSON 合同',
        status: Number.isInteger(response?.status) ? response.status : null,
        estimatedRequestBodyBytes,
        maxRequestBodyBytes,
        retryable: false,
    });
}

function _recordTransportError(entry, error) {
    entry.http_status = error.status;
    entry.code = error.code;
    entry.estimated_request_body_bytes = error.estimatedRequestBodyBytes;
    entry.max_request_body_bytes = error.maxRequestBodyBytes;
    if (
        Number.isSafeInteger(error.maxRequestBodyBytes)
        && error.maxRequestBodyBytes > 0
    ) {
        state.legacyJsonBase64MaxRequestBodyBytes = error.maxRequestBodyBytes;
    }
}

function _recordAnalyzePayload(runEntry, payload, httpStatus) {
    runEntry.http_status = httpStatus;
    if (!_isRecord(payload)) return;
    runEntry.code = typeof payload.code === 'string' ? payload.code : null;
    runEntry.recovery = typeof payload.recovery === 'string' ? payload.recovery : null;
    runEntry.reasons = _backendReasons(payload);
    runEntry.trace_id = typeof payload.trace_id === 'string' ? payload.trace_id : null;
    runEntry.debug_log = payload.debug_log || null;
    runEntry.dimensions = payload.dimensions || null;
    runEntry.basic_dimensions = payload.basic_dimensions || null;
    runEntry.references = payload.references || null;
    runEntry.view_boxes = payload.view_boxes || null;
    runEntry.review_candidates_v1 = Object.hasOwn(payload, REVIEW_CANDIDATES_ROOT_KEY)
        ? payload[REVIEW_CANDIDATES_ROOT_KEY]
        : null;
    runEntry.r33_m1_phrase_chain_audit_v1 = Object.hasOwn(
        payload,
        'r33_m1_phrase_chain_audit_v1',
    ) ? payload.r33_m1_phrase_chain_audit_v1 : null;
    runEntry.timings = payload.timings || null;
    runEntry.ocr_breakdown = payload.ocr_breakdown || null;
    runEntry.ocr_pass_counters = payload.ocr_pass_counters || null;
}

function _strictVectorOnlyAnalysisBlock(source = state) {
    if (source.recognitionSettings?.dimension_path !== 'vector_only') return null;

    const status = source.recognitionCapabilitiesStatus;
    if (status === 'idle') return null;
    if (!['loading', 'error', 'ready'].includes(status)) return null;

    const vectorOnlyRow = computeDimensionPathRowStates(
        source.strictViewSegCapability,
        source.strictTemplateCapability,
    ).find(row => row.path === 'vector_only');
    if (status === 'ready' && !vectorOnlyRow?.disabled) return null;

    return {
        status,
        error: typeof source.recognitionCapabilitiesError === 'string'
            ? source.recognitionCapabilitiesError.trim()
            : '',
        reasons: [...new Set(
            (vectorOnlyRow?.reasons || [])
                .filter(reason => typeof reason === 'string' && reason),
        )],
    };
}

function _formatStrictVectorOnlyBlockAlert(block) {
    const lines = ['严格矢量识别暂不可用，未发送分析请求。'];
    if (block.status === 'loading') {
        lines.push('能力检测仍在进行，请稍后再试。');
    } else if (block.status === 'error') {
        lines.push(`能力检测失败${block.error ? `：${block.error}` : '。'}`);
    } else {
        lines.push('严格运行资产未就绪。');
    }
    if (block.reasons.length > 0) {
        lines.push(`reasons: ${block.reasons.join(', ')}`);
    }
    const recoveryGuidance = block.reasons
        .map(formatStrictRuntimeReason)
        .find(Boolean);
    if (recoveryGuidance) lines.push(`恢复指引：${recoveryGuidance}。`);
    lines.push('请在高级设置中重试能力检测；如需继续，请手动切换到兼容识别模式。');
    return lines.join('\n');
}


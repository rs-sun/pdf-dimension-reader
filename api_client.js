// 尺寸表 Excel 导出（POST /export）
// 返回 Blob（xlsx 二进制）；交互失败返回 null；silent 失败原样抛回事务层。
// =============================================================================

export async function runExportXlsx(pageNumber, { partNo, allPages = false, silent = false, dims = null } = {}) {
    if (!state.currentPdfBuffer) {
        if (!silent) alert('请先打开图纸文档！');
        return null;
    }

    const controller = new AbortController();
    const timeoutId  = setTimeout(() => controller.abort(), 300000);

    // dims 传值（前端校对后的 dim 列表）= 后端跳过 pipeline 直接生成 Excel；
    // null 时保留旧行为：后端重跑 pipeline。
    const requestFields = {
        page:      pageNumber,
        all_pages: allPages,
        part_no:   partNo || 'drawing',
    };
    if (dims !== null && Array.isArray(dims)) {
        requestFields.dims = dims;
    }

    const t0 = performance.now();
    const callEntry = {
        ts: new Date().toISOString(),
        page: pageNumber,
        allPages,
        partNo: requestFields.part_no,
        dimsCount: Array.isArray(dims) ? dims.length : null,
        silent,
        durationMs: 0,
        ok: false,
        error: null,
        code: null,
        http_status: null,
        estimated_request_body_bytes: null,
        max_request_body_bytes: state.legacyJsonBase64MaxRequestBodyBytes,
    };

    try {
        const preparedRequest = prepareJsonBase64Body(
            state.currentPdfBuffer,
            requestFields,
            state.legacyJsonBase64MaxRequestBodyBytes,
        );
        callEntry.estimated_request_body_bytes = preparedRequest.requestBodyBytes;
        const response = await fetch(EXPORT_URL, {
            method:  'POST',
            headers: { 'Content-Type': 'application/json' },
            body:    preparedRequest.body,
            signal:  controller.signal,
        });
        callEntry.http_status = response.status;

        if (!response.ok) {
            const payload = await readResponsePayload(response);
            throw normalizeTransportError(response, payload, {
                estimatedRequestBodyBytes: preparedRequest.requestBodyBytes,
                maxRequestBodyBytes: state.legacyJsonBase64MaxRequestBodyBytes,
            });
        }
        const blob = await response.blob();
        callEntry.ok = true;
        return blob;

    } catch (err) {
        callEntry.error = err.name === 'AbortError' ? 'timeout(300s)' : (err.message || String(err));
        if (err.name === 'AbortError') {
            callEntry.code = 'client_deadline_exceeded';
        } else if (err instanceof TransportError) {
            _recordTransportError(callEntry, err);
        }
        if (silent) {
            console.warn('[runExportXlsx] 失败:', err.message || err);
            throw err;
        } else if (err.name === 'AbortError') {
            alert('Excel 导出超时（300s）！请检查后端服务。');
        } else if (err instanceof TransportError) {
            alert(_formatTransportErrorAlert('Excel 导出失败', err));
        } else {
            alert('Excel 导出失败：\n' + err.message);
        }
        return null;
    } finally {
        clearTimeout(timeoutId);
        callEntry.durationMs = Math.round(performance.now() - t0);
        pushBounded(state.exportCalls, callEntry, DEBUG_LOG_CAPS.exportCalls);
    }
}


// =============================================================================
// 检验结果导入（POST /import_measurements）
// =============================================================================

export async function runImportMeasurements(files) {
    const list = Array.from(files || []);
    if (list.length === 0) {
        alert('请选择测量结果 Excel 文件。');
        return null;
    }

    const form = new FormData();
    list.forEach(file => form.append('files', file, file.name));

    try {
        const response = await fetch(IMPORT_MEASUREMENTS_URL, {
            method: 'POST',
            body: form,
        });
        const result = await response.json().catch(() => ({}));
        if (!response.ok || result.status !== 'success') {
            throw new Error(result.message || `HTTP ${response.status} ${response.statusText}`);
        }
        return result;
    } catch (err) {
        alert('测量结果导入失败：\n' + (err.message || err));
        return null;
    }
}



/**
 * @param {number} pageIndex  1-based 页码
 * @param {{x,y,w,h}} cropBbox  PDF 坐标系（72 DPI），左上角原点
 * @param {number} [dpi=300]    后端渲染 DPI
 * @param {string} [stampUuid]  关联的 stamp uuid（仅用于调试日志，非必需）
 * @returns {Promise<{text:string, candidates:Array}|null>}
 */
export async function runStampOCR(pageIndex, cropBbox, dpi = 300, stampUuid = null) {
    if (!state.currentPdfBuffer) return null;

    const controller = new AbortController();
    const timeoutId  = setTimeout(() => controller.abort(), 30000);  // 小区域 OCR，30s 足够

    const t0 = performance.now();
    const callEntry = {
        ts: new Date().toISOString(),
        page: pageIndex,
        cropBbox: { ...cropBbox },
        stampUuid,
        dpi,
        durationMs: 0,
        ok: false,
        response: null,
        error: null,
        code: null,
        http_status: null,
        estimated_request_body_bytes: null,
        max_request_body_bytes: state.legacyJsonBase64MaxRequestBodyBytes,
    };

    try {
        const preparedRequest = prepareJsonBase64Body(
            state.currentPdfBuffer,
            {
                page: pageIndex,
                crop_bbox: cropBbox,
                dpi,
            },
            state.legacyJsonBase64MaxRequestBodyBytes,
        );
        callEntry.estimated_request_body_bytes = preparedRequest.requestBodyBytes;
        const response = await fetch(ANALYZE_STAMP_URL, {
            method:  'POST',
            headers: { 'Content-Type': 'application/json' },
            body:    preparedRequest.body,
            signal:  controller.signal,
        });
        callEntry.http_status = response.status;
        const result = await readResponsePayload(response);
        if (!response.ok) {
            throw normalizeTransportError(response, result, {
                estimatedRequestBodyBytes: preparedRequest.requestBodyBytes,
                maxRequestBodyBytes: state.legacyJsonBase64MaxRequestBodyBytes,
            });
        }
        if (!_isRecord(result)) {
            throw _invalidResponsePayloadError(response, {
                estimatedRequestBodyBytes: preparedRequest.requestBodyBytes,
                maxRequestBodyBytes: state.legacyJsonBase64MaxRequestBodyBytes,
            });
        }

        if (result.status !== 'success') {
            callEntry.error = result.message || 'status!=success';
            callEntry.response = { text: result.text || '', candidates: result.candidates || [] };
            return null;
        }
        const ret = { text: result.text || '', candidates: result.candidates || [] };
        callEntry.response = ret;
        callEntry.ok = true;
        return ret;

    } catch (err) {
        callEntry.error = err.name === 'AbortError' ? 'timeout(30s)' : (err.message || String(err));
        if (err.name === 'AbortError') {
            callEntry.code = 'client_deadline_exceeded';
        } else if (err instanceof TransportError) {
            _recordTransportError(callEntry, err);
        }
        console.warn('[runStampOCR] failed silently:', err.message || err);
        return null;
    } finally {
        clearTimeout(timeoutId);
        callEntry.durationMs = Math.round(performance.now() - t0);
        pushBounded(state.stampOcrCalls, callEntry, DEBUG_LOG_CAPS.stampOcrCalls);
    }
}



// 监听 canvas_renderer / app_cursor 派发的事件
document.addEventListener('pdf-reader:transform-update', repositionStampPopup);
document.addEventListener('pdf-reader:selection-change', updateStampPopup);

// 拖拽：popup 上 mousedown 启动；window 上 move/up（避免鼠标飞出 popup 时丢追踪）
document.addEventListener('DOMContentLoaded', () => {
    const popup = document.getElementById('stamp-popup');
    if (popup) popup.addEventListener('mousedown', _onPopupMouseDown);
});
// 兼容已加载完的场景（DOMContentLoaded 已 fire）
{
    const popup = document.getElementById('stamp-popup');
    if (popup) popup.addEventListener('mousedown', _onPopupMouseDown);
}
window.addEventListener('mousemove', _onPopupMouseMove);
window.addEventListener('mouseup', _onPopupMouseUp);
